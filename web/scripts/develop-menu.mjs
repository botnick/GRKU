// Writes src/develop/menu.ts: the camera menu text of the modules that the Develop page runs, from
// modules/<module>/text/<language>.toml, so the page names each setting and value as the camera
// does. src/develop/menu.test.ts checks that the file matches the module text.
//
//   node scripts/develop-menu.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const modules = resolve(web, '..', 'modules');

/** The modules of the page and their directories. */
export const MENU_MODULES = { grain: 'grain', glow: 'glow', leak: 'lightleak', diffusion: 'diffusion', date: 'date', border: 'border' };
/** The camera menu languages (the camera has no Thai menu). */
export const MENU_LANGUAGES = ['en', 'zh-Hans', 'zh-Hant', 'ja', 'ko'];

/** The text of a module text file: title, rows, and the label and values of each setting and child. */
export function parseText(toml) {
  const out = { title: '', settings: {}, children: {} };
  let section = out;
  for (const raw of toml.split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const header = /^\[(settings|children)\.(?:"([^"]+)"|([A-Z0-9_]+))\]$/.exec(line);
    if (header) {
      const key = header[2] ?? header[3];
      section = out[header[1]][key] = {};
      continue;
    }
    const pair = /^([a-z_]+)\s*=\s*(.+)$/.exec(line);
    if (!pair) throw new Error(`Cannot read: ${line}`);
    section[pair[1]] = JSON.parse(pair[2]);
  }
  return out;
}

export function menuSource() {
  const menu = {};
  for (const language of MENU_LANGUAGES) {
    menu[language] = {};
    for (const [name, dir] of Object.entries(MENU_MODULES)) {
      menu[language][name] = parseText(readFileSync(join(modules, dir, 'text', `${language}.toml`), 'utf8'));
    }
  }
  return [
    '// Generated by scripts/develop-menu.mjs from modules/*/text/*.toml: the camera menu text of the',
    '// modules of the Develop page. Do not edit: change the module text, then run the script.',
    '',
    'export interface MenuSetting {',
    '  label?: string;',
    '  values?: readonly string[];',
    '}',
    '',
    'export interface ModuleMenu {',
    '  title: string;',
    '  rows?: readonly string[];',
    '  settings: Readonly<Record<string, MenuSetting>>;',
    '  children: Readonly<Record<string, { title?: string }>>;',
    '}',
    '',
    'export const MENU = {',
    ...Object.entries(menu).flatMap(([language, items]) => [
      `  ${JSON.stringify(language)}: {`,
      ...Object.entries(items).map(([name, text]) => `    ${name}: ${JSON.stringify(text)},`),
      '  },',
    ]),
    '} as const satisfies Readonly<Record<string, Readonly<Record<string, ModuleMenu>>>>;',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(web, 'src', 'develop', 'menu.ts'), menuSource());
}
