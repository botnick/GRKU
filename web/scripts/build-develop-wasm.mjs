// Builds the picture modules for the browser: web/src/wasm/develop.wasm, which the Develop page
// (src/develop/) runs in a worker. The module sources of modules/ build for wasm32 with their
// scalar C paths (the NEON paths are for the camera), with the harness of web/develop/ in place
// of the camera core.
//
//   node scripts/build-develop-wasm.mjs
//
// It needs clang with the WebAssembly target (Apple clang and the clang of Ubuntu have it) and
// wasm-ld: WASM_LD, wasm-ld on the PATH, or the one of the Rust toolchain (rustup's rust-lld).
// CLANG names another clang.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const root = resolve(web, '..');
const output = join(web, 'src', 'wasm', 'develop.wasm');

/** The modules of the build: the directory, the sources (besides web/develop/modules.c), and the define of the glue. */
const MODULES = [
  { dir: 'date', sources: ['stamp.c'], define: 'DEVELOP_DATE' },
  { dir: 'glow', sources: ['glow.c', 'glow_kernels.c'], define: 'DEVELOP_GLOW' },
  // modules.c includes lightleak.c and grain.c itself.
  { dir: 'lightleak', sources: [], define: 'DEVELOP_LEAK' },
  { dir: 'diffusion', sources: ['diffusion.c', 'softness.c', 'softness_kernels.c'], define: 'DEVELOP_DIFFUSION' },
  { dir: 'grain', sources: [], define: 'DEVELOP_GRAIN' },
];

function which(name) {
  try {
    return execFileSync('sh', ['-c', `command -v ${name}`], { encoding: 'utf8' }).trim() || null;
  } catch {
    return null;
  }
}

/** wasm-ld: WASM_LD, the PATH, or the linker of the Rust toolchain. */
function linker() {
  if (process.env.WASM_LD) return process.env.WASM_LD;
  const found = which('wasm-ld');
  if (found) return found;
  const sysroot = execFileSync('rustc', ['--print', 'sysroot'], { encoding: 'utf8' }).trim();
  const host = /^host: (.+)$/m.exec(execFileSync('rustc', ['-vV'], { encoding: 'utf8' }))?.[1];
  const candidate = join(sysroot, 'lib', 'rustlib', host ?? '', 'bin', 'gcc-ld', 'wasm-ld');
  if (existsSync(candidate)) return candidate;
  throw new Error('No wasm-ld: install lld, or set WASM_LD');
}

/**
 * The settings header of a module, as `grku module build` writes it from module.toml: setting k
 * is GRKU_SETTING(k) in the order of [[settings]], used setting k GRKU_USED(k) in the order of `uses`.
 */
export function settingsHeader(manifest, id) {
  const keys = [...manifest.matchAll(/^\[\[settings\]\]\s*\n(?:\s*#.*\n)*\s*key\s*=\s*"([A-Z0-9_]+)"/gm)].map((m) => m[1]);
  const uses = [...(/^uses\s*=\s*\[([^\]]*)\]/m.exec(manifest)?.[1] ?? '').matchAll(/"([A-Z0-9_.]+)"/g)].map((m) => m[1]);
  const lines = [
    '/* Generated by web/scripts/build-develop-wasm.mjs from module.toml. */',
    `#ifndef GRKU_MODULE_${id}_H`,
    `#define GRKU_MODULE_${id}_H`,
    '#include "grku.h"',
    ...keys.map((key, k) => `#define SETTING_${key} GRKU_SETTING(${k})`),
    ...uses.map((key, k) => `#define USED_${key.replace('.', '_')} GRKU_USED(${k})`),
    '#endif',
    '',
  ];
  return lines.join('\n');
}

const clang = process.env.CLANG ?? 'clang';
const wasmLd = linker();
const work = mkdtempSync(join(tmpdir(), 'grku-develop-'));
try {
  const flags = [
    '--target=wasm32',
    '-std=c11',
    '-O3',
    '-ffreestanding',
    '-fno-exceptions',
    '-ffunction-sections',
    '-fdata-sections',
    '-mbulk-memory',
    '-mnontrapping-fptoint',
    '-msign-ext',
    '-Wall',
    '-Wno-unused-function',
    '-Wno-gnu-flexible-array-initializer',
    '-I', join(root, 'runtime', 'sdk'),
    '-I', join(web, 'develop'),
  ];
  const objects = [];
  const compile = (source, extra, name) => {
    const object = join(work, `${name}.o`);
    execFileSync(clang, [...flags, ...extra, '-c', source, '-o', object], { stdio: ['ignore', 'inherit', 'inherit'] });
    objects.push(object);
  };
  for (const file of ['develop.c', 'jpeg.c']) {
    compile(join(web, 'develop', file), ['-include', join(web, 'develop', 'develop.h')], file.replace('.c', ''));
  }
  compile(join(web, 'develop', 'libc.c'), ['-fno-builtin'], 'libc');
  for (const module of MODULES) {
    const dir = join(root, 'modules', module.dir);
    const manifest = readFileSync(join(dir, 'module.toml'), 'utf8');
    const id = /^id\s*=\s*"([A-Z0-9_]+)"/m.exec(manifest)[1];
    const headers = join(work, module.dir);
    mkdirSync(headers);
    writeFileSync(join(headers, 'grku_module.h'), settingsHeader(manifest, id));
    const extra = ['-include', join(web, 'develop', 'develop.h'), '-I', headers, '-I', dir, `-D${module.define}`];
    for (const source of module.sources) compile(join(dir, source), extra, `${module.dir}-${source.replace('.c', '')}`);
    compile(join(web, 'develop', 'modules.c'), extra, `${module.dir}-glue`);
  }
  mkdirSync(dirname(output), { recursive: true });
  execFileSync(wasmLd, ['--no-entry', '--strip-all', '--gc-sections', '-O3', '--stack-first', '-z', 'stack-size=1048576', ...objects, '-o', output], {
    stdio: ['ignore', 'inherit', 'inherit'],
  });
  console.log(`develop.wasm: ${(statSync(output).size / 1024).toFixed(0)} KB`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
